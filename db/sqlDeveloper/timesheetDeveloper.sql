  SELECT
    e.employee_id,
    e.full_name,
    SUM(y.quantity) AS total_hours,
    RANK() OVER (ORDER BY SUM(y.quantity) DESC) AS rank_by_hours
FROM
    employee e
    JOIN timecard t ON t.employee_id = e.employee_id
    JOIN entry y ON y.timecard_id = t.timecard_id 
WHERE
    y.time_type_id IN (1, 2)
GROUP BY
    e.employee_id, e.full_name
;
