  CREATE OR REPLACE FORCE EDITIONABLE VIEW "TIMESHEET"."VW_ALL_TIMECARDS" ("TIMECARD_ID", "FULL_NAME", "START_DATE", "END_DATE", "NUMBER_OF_ENTRIES") AS 
  SELECT
    t.timecard_id,
    e.full_name,
    t.start_date,
    t.end_date,
    COUNT(y.entry_id) AS number_of_entries
FROM
    timecard t 
    JOIN employee e ON e.employee_id = t.employee_id
    LEFT JOIN entry y ON t.timecard_id = y.timecard_id 
GROUP BY
    t.timecard_id, e.full_name, t.start_date, t.end_date
;
