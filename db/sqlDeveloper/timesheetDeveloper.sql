  CREATE OR REPLACE FORCE EDITIONABLE VIEW "TIMESHEET"."VW_EMPLOYEE_WORKED_HOURS" ("EMPLOYEE_ID", "FULL_NAME", "START_DATE", "END_DATE", "HOURS_WORKED") AS 
  SELECT 
    e.employee_id, 
    e.full_name, 
    t.start_date,
    t.end_date,
    SUM(y.quantity) AS hours_worked 
FROM 
    employee e
    JOIN timecard t ON e.employee_id = t.employee_id 
    JOIN entry y ON t.timecard_id = y.timecard_id
WHERE 
    y.time_type_id IN (1,2)
    AND y.entry_date BETWEEN t.start_date AND t.end_date
GROUP BY 
    e.employee_id, e.full_name, t.start_date, t.end_date
;
